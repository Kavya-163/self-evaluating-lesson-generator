import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUTPUTS = ROOT / "outputs"
MEMORY_PATH = OUTPUTS / "memory.json"
MAX_RETRIES = 2

RUBRIC = [
    "accuracy",
    "beginner_language",
    "example",
    "jargon",
    "coverage",
    "flow",
    "minimum_structure",
    "has_limitations"
]


def load_memory():
    if MEMORY_PATH.exists():
        try:
            return json.loads(MEMORY_PATH.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            pass

    return {"runs": [], "learned_guidance": []}


def save_memory(memory):
    OUTPUTS.mkdir(parents=True, exist_ok=True)
    MEMORY_PATH.write_text(
        json.dumps(memory, indent=2, ensure_ascii=False),
        encoding="utf-8"
    )


def generate_lesson(topic, feedback, memory):
    lesson = f"""
# {topic}

## 1. What is RAG?

RAG stands for Retrieval-Augmented Generation. It is a method used in
Artificial Intelligence (AI). AI means computer systems that perform
tasks that normally need human intelligence.

RAG combines two steps: retrieval and generation. Retrieval means
finding useful information from stored documents. Generation means
using that information to create an answer.

In simple words, RAG helps an AI system find information before
answering a question.

## 2. Why is RAG useful?

An AI model may not know the latest or private information.
RAG helps by finding relevant information from an external source.

For example, a college can store its rules, fee details, and course
information in documents. Students can ask questions about them.
RAG can find the relevant information and prepare an answer.

## 3. How does RAG work?

The process has these steps:

1. Documents are collected from trusted sources.
2. Each document is divided into smaller parts called chunks.
   A chunk is simply a small piece of a larger document.
3. An embedding is created for each chunk. An embedding is a list
   of numbers that represents the meaning of text.
4. These embeddings are stored in a vector database.
   A vector database stores and searches information using these
   number representations.
5. When a user asks a question, the system searches for related chunks.
6. This search process is called retrieval.
7. The retrieved information is given to the language model.
8. The model uses the information to generate an answer.

## 4. Everyday example

Imagine a student asking a college chatbot:
"What is the last date to pay my examination fee?"

Step 1: The student enters the question.

Step 2: The RAG system searches the college documents.

Step 3: It finds the document containing the examination fee deadline.

Step 4: The relevant text is sent to the AI model.

Step 5: The AI model prepares an answer using the retrieved information.

This makes the answer more useful than relying only on the model's
previous training.

## 5. Benefits of RAG

- It can use updated information from documents.
- It can answer questions about private company or college documents.
- It can provide source information for answers.
- It can reduce some incorrect answers.

## 6. Limitations of RAG

RAG does not guarantee that every answer is correct.
The documents may be incomplete, outdated, or incorrect.
The system may also retrieve information that is not relevant.

A hallucination is an answer generated by AI that sounds correct
but contains incorrect or unsupported information.

Therefore, important answers should be checked against trusted sources.

## 7. When is RAG useful?

RAG is useful for college chatbots, customer support systems,
company document search, question-answering applications,
and knowledge assistants.

## 8. Quick recap

RAG means Retrieval-Augmented Generation.
It first retrieves useful information and then generates an answer.
It can make AI answers more relevant, but it does not guarantee truth.
Always check important information using reliable sources.
"""
    return lesson


def inject_deliberate_error(lesson):
    return lesson + """

## Deliberate test statement

RAG guarantees that every answer is always correct because
retrieved documents cannot contain mistakes.
"""


def evaluate_lesson(lesson):
    text = lesson.lower()
    checks = []

    false_claim = (
        "rag guarantees that every answer is always correct"
        in text
    )

    checks.append({
        "id": "accuracy",
        "status": "FAIL" if false_claim else (
            "PASS" if "retrieval" in text
            and "generation" in text
            and "does not guarantee" in text
            else "FAIL"
        ),
        "reason": (
            "False claim detected: RAG cannot guarantee that every answer is correct."
            if false_claim else
            "RAG is defined correctly and its limitations are explained."
        )
    })

    checks.append({
        "id": "beginner_language",
        "status": "PASS" if "in simple words" in text else "FAIL",
        "reason": "Simple explanation is present."
    })

    checks.append({
        "id": "example",
        "status": "PASS" if all(
            word in text for word in
            ["everyday example", "step 1", "step 5"]
        ) else "FAIL",
        "reason": "A step-by-step everyday example is included."
    })

    terms = ["embedding", "vector database", "chunk",
             "retrieval", "hallucination"]

    checks.append({
        "id": "jargon",
        "status": "PASS" if all(term in text for term in terms)
        else "FAIL",
        "reason": "Important technical terms are explained."
    })

    sections = [
        "benefits", "limitations", "when is rag useful",
        "how does rag work"
    ]

    checks.append({
        "id": "coverage",
        "status": "PASS" if all(
            section in text for section in sections
        ) else "FAIL",
        "reason": "Key learning topics are covered."
    })

    checks.append({
        "id": "flow",
        "status": "PASS" if text.find("what is rag")
        < text.find("why is rag useful")
        < text.find("how does rag work")
        < text.find("everyday example")
        < text.find("quick recap") else "FAIL",
        "reason": "Lesson follows a logical teaching order."
    })

    checks.append({
        "id": "minimum_structure",
        "status": "PASS" if len(lesson.split()) >= 250
        else "FAIL",
        "reason": "Lesson contains at least 250 words."
    })

    checks.append({
        "id": "has_limitations",
        "status": "PASS" if "does not guarantee" in text
        and "incomplete" in text else "FAIL",
        "reason": "Reliability limitations are explained."
    })

    overall = (
        "PASS" if all(c["status"] == "PASS" for c in checks)
        else "FAIL"
    )

    feedback = [
        f"Fix {c['id']}: {c['reason']}"
        for c in checks if c["status"] == "FAIL"
    ]

    return {
        "checks": checks,
        "overall": overall,
        "revision_instructions": feedback
    }


def run(topic, inject_error=False):
    OUTPUTS.mkdir(parents=True, exist_ok=True)

    memory = load_memory()
    rejection_log = []
    final_lesson = ""
    final_eval = {}
    attempts_used = 0

    for attempt in range(MAX_RETRIES + 1):
        attempts_used += 1

        lesson = generate_lesson(
            topic,
            memory.get("learned_guidance", []),
            memory
        )

        if inject_error and attempt == 0:
            lesson = inject_deliberate_error(lesson)

        evaluation = evaluate_lesson(lesson)

        print(
            f"Attempt {attempt + 1}: {evaluation['overall']}"
        )

        if evaluation["overall"] == "PASS":
            final_lesson = lesson
            final_eval = evaluation
            break

        failed = [
            c for c in evaluation["checks"]
            if c["status"] == "FAIL"
        ]

        rejection_log.append({
            "attempt": attempt + 1,
            "failed_checks": [c["id"] for c in failed],
            "reasons": [c["reason"] for c in failed],
            "changes_requested": evaluation["revision_instructions"]
        })

        for item in evaluation["revision_instructions"]:
            if item not in memory["learned_guidance"]:
                memory["learned_guidance"].append(item)

        final_lesson = lesson
        final_eval = evaluation

    passed = final_eval.get("overall") == "PASS"

    result = {
        "topic": topic,
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "status": "SHIPPED" if passed else "NOT_SHIPPED",
        "attempts_used": attempts_used,
        "max_retries": MAX_RETRIES,
        "evaluation": final_eval,
        "rejection_log": rejection_log,
        "lesson": final_lesson
    }

    (OUTPUTS / "final_lesson.md").write_text(
        final_lesson, encoding="utf-8"
    )

    (OUTPUTS / "run_report.json").write_text(
        json.dumps(result, indent=2, ensure_ascii=False),
        encoding="utf-8"
    )

    memory["runs"].append({
        "topic": topic,
        "status": result["status"],
        "attempts_used": attempts_used,
        "rejection_count": len(rejection_log)
    })

    save_memory(memory)

    print("\nFinal status:", result["status"])
    print("Attempts used:", attempts_used)
    print("Lesson saved in:", OUTPUTS / "final_lesson.md")
    print("Report saved in:", OUTPUTS / "run_report.json")
    print("Memory saved in:", MEMORY_PATH)

    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--topic", default="Introduction to RAG"
    )
    parser.add_argument(
        "--inject-error",
        action="store_true",
        help="Insert a false claim to test the evaluator."
    )

    args = parser.parse_args()
    run(args.topic, args.inject_error)